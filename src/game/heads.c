    // asm 0000A277: SLEEP	1
    SLEEP(1, 1);
    // asm 0000A279: 	LDF	*+AR4(TEXT_POSX),R0
    position = C3X_LDF(p->ctx.KRIS.front->posx);
    // asm 0000A27A: 	FLOAT	259,R1
