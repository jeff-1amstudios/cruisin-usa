static void SET18FONTDS_WHITE(tSHADOW_TEXT* text) {
    int palette;

    // asm 0000A20F: 	CALL	SET18FONTDS
    SET18FONTDS(text);
    // asm 0000A210: 	LDL	font18_white,AR2
    // asm 0000A211: 	CALL	PAL_FIND_RAW
    palette = PAL_FIND_RAW((tPAL*)ROM_PTR(font18_white_ROM));
    // asm 0000A212: 	STI	R0,*+AR0(TEXT_PAL)
    // asm 0000A213: 	STI	R0,*+AR1(TEXT_PAL)
    text->front->palette = palette;
    text->shadow->palette = palette;
    // asm 0000A214: 	RETS
}

